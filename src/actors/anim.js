// Reusable carry poses so the clips below stay readable.
//
// Low ready: both hands on the weapon, muzzle forward and down. The elbows are
// deliberately WELL flexed. The support hand has to reach the foregrip, and the
// left arm is only 52 cm long: at the old 58-degree gun-elbow the foregrip
// landed 64 cm from the left shoulder, so the support arm locked out straight
// with the hand hanging in mid-air 8 cm short of the wood. Keeping the gun
// elbow near 85 degrees tucks the weapon in against the chest where a soldier
// at low ready actually carries it, and the support hand lands on the grip.
// ROUND 10 — THE ARMS WERE GLUED TO THE RIBCAGE, and that is the whole of the
// "rectangular slab between collar and belt" note that has stood for four
// rounds. Measured on the round-9 closeup by projecting the skeleton into screen
// space: the trunk is not on the silhouette AT ALL. The left edge of the figure
// is upperArmR's sleeve and the right edge is upperArmL's, so what reads as a
// slab is TWO VERTICAL SLEEVES bracketing a body they share an albedo with and
// draw no ink against. (Control: shrinking the trunk tube 45% as a probe moved
// 1.66% of the frame. It is not the trunk.)
//
// The cause is here. `+Z swings toward the character's LEFT`, so uR z = +9 and
// uL z = -12 were ADDUCTING both humeri 9-12 degrees INTO the ribs. A soldier at
// low ready does tuck, but the tuck is at the ELBOW; the humerus still hangs a
// few degrees clear, and that clearance is the wedge of shade that separates arm
// from body in every drawing ever made of one. Every carry-family key in this
// file now abducts instead (uR z -11, uL z +18 across the board, leaving the
// shouldered AIMED pose and the prone/death chains alone), which is 11 and 18
// degrees of swing and moves the hands 40-60 mm outboard — well inside what the
// support-hand IK and the weapon-hold solver re-converge on.
