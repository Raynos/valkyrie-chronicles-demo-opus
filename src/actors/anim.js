/** Non-uniform Catmull-Rom (Hermite with central-difference tangents). */
function crEval(times, vals, comp, i, u, h) {
  const n = times.length;
  const im = i - 1 < 0 ? 0 : i - 1;
  const ip = i + 1 >= n ? n - 1 : i + 1;
  const ipp = i + 2 >= n ? n - 1 : i + 2;
  const p0 = vals[i][comp], p1 = vals[ip][comp];
  const dtA = Math.max(1e-6, times[ip] - times[im]);
  const dtB = Math.max(1e-6, times[ipp] - times[i]);
  const m0 = (vals[ip][comp] - vals[im][comp]) / dtA * h;
  const m1 = (vals[ipp][comp] - vals[i][comp]) / dtB * h;
  const u2 = u * u, u3 = u2 * u;
  return (2 * u3 - 3 * u2 + 1) * p0 + (u3 - 2 * u2 + u) * m0 +
    (-2 * u3 + 3 * u2) * p1 + (u3 - u2) * m1;
}

/**
 * Resample a sparse (time, vec3) sample list onto `outTimes`.
 * Loops get wrapped tangents so the cycle is C1 across the seam.
 */
function resample(samples, dur, outTimes, loop, dims) {
  let times = samples.map((s) => s[0]);
  let vals = samples.map((s) => s[1]);
  if (times.length === 1) return outTimes.map(() => vals[0].slice());

  if (loop) {
    // Guarantee an explicit end key equal to the start so the wrap is exact.
    if (Math.abs(times[times.length - 1] - dur) > 1e-6) { times = times.concat([dur]); vals = vals.concat([vals[0].slice()]); }
    times = [times[times.length - 2] - dur].concat(times, [times[1] + dur]);
    vals = [vals[vals.length - 2].slice()].concat(vals, [vals[1].slice()]);
  }

  const out = [];
  let i = loop ? 1 : 0;
  const last = loop ? times.length - 3 : times.length - 2;
  for (const t of outTimes) {
    while (i < last && t > times[i + 1]) i++;
    while (i > (loop ? 1 : 0) && t < times[i]) i--;
    const h = Math.max(1e-6, times[i + 1] - times[i]);
    const u = clamp01((t - times[i]) / h);
    const v = new Array(dims);
    for (let c = 0; c < dims; c++) v[c] = crEval(times, vals, c, i, u, h);
    out.push(v);
  }
  return out;
}

const _clipCache = new Map();

/**
 * Compile the whole catalogue for a rig variant. Cached by rig.variantKey so a
 * 14-strong squad with 5 body types builds 5 clip sets, not 14.
 * @returns {Object<string, THREE.AnimationClip>}
 */
export function buildClipSet(rig) {
  const key = rig.variantKey;
  const hit = _clipCache.get(key);
  if (hit) return hit;

  const set = Object.create(null);
  for (const name in CLIP_DEFS) set[name] = compileClip(name, CLIP_DEFS[name], rig);
  _clipCache.set(key, set);
  return set;
}

function compileClip(name, def, rig) {
  const dur = def.dur;
  const boneSet = def.upper ? UPPER : ANIMATED;

  // --- gather per-bone sparse samples ------------------------------------
  const samples = Object.create(null);
  const hipsPos = [];
  for (const [ft, pose] of def.keys) {
    const t = ft * dur;
    for (const short in pose) {
      if (short === 'hP') { hipsPos.push([t, pose.hP.slice()]); continue; }
      const bone = A[short] || short;
      (samples[bone] || (samples[bone] = [])).push([t, pose[short].slice()]);
    }
  }

  // --- mirror expansion ---------------------------------------------------
  // Author one side; the other is (x, -y, -z) shifted by `mirror` of a cycle.
  const shift = (def.mirror || 0) * dur;
  for (const bone in Object.assign({}, samples)) {
    if (!bone.endsWith('L')) continue;
    const other = bone.slice(0, -1) + 'R';
    if (samples[other] || boneSet.indexOf(other) < 0) continue;
    const src = samples[bone];
    const dst = src.map(([t, v]) => [(t + shift) % dur, [v[0], -v[1], -v[2]]]);
    dst.sort((a, b) => a[0] - b[0]);
    if (def.loop && shift > 0) {
      // Re-close the cycle after the phase shift.
      const first = dst[0], lastS = dst[dst.length - 1];
      if (first[0] > 1e-6) dst.unshift([0, lastS[1].slice()]);
      if (Math.abs(lastS[0] - dur) > 1e-6) dst.push([dur, dst[0][1].slice()]);
    }
    samples[other] = dst;
  }

  // --- output sample grid -------------------------------------------------
  const n = Math.max(3, Math.round(dur * RESAMPLE_FPS));
  const outTimes = new Array(n + 1);
  for (let i = 0; i <= n; i++) outTimes[i] = (i / n) * dur;

  const tracks = [];
  const restZero = [0, 0, 0];

  for (const bone of boneSet) {
    const rest = rig.restLocal[bone];
    if (!rest) continue;
    const src = samples[bone];
    let vals;
    if (!src || src.length === 0) {
      vals = null;                                  // constant at rest
    } else {
      src.sort((a, b) => a[0] - b[0]);
      vals = resample(src, dur, outTimes, !!def.loop, 3);
    }

    // Constant tracks collapse to two keys.
    let constant = true;
    if (vals) {
      const v0 = vals[0];
      for (const v of vals) {
        if (Math.abs(v[0] - v0[0]) > 0.02 || Math.abs(v[1] - v0[1]) > 0.02 || Math.abs(v[2] - v0[2]) > 0.02) { constant = false; break; }
      }
    }
    const times = constant ? [0, dur] : outTimes;
    const count = times.length;
    const buf = new Float32Array(count * 4);
    for (let i = 0; i < count; i++) {
      const v = vals ? (constant ? vals[0] : vals[i]) : restZero;
      _e.set(v[0] * DEG, v[1] * DEG, v[2] * DEG, 'XYZ');
      _q.setFromEuler(_e);
      // Delta is applied in the bone's own rest frame: q = rest * delta.
      _q.premultiply(rest.quat);
      buf[i * 4] = _q.x; buf[i * 4 + 1] = _q.y; buf[i * 4 + 2] = _q.z; buf[i * 4 + 3] = _q.w;
    }
    // Keep neighbouring quaternions in the same hemisphere so slerp is short.
    for (let i = 1; i < count; i++) {
      const a = (i - 1) * 4, b = i * 4;
      const d = buf[a] * buf[b] + buf[a + 1] * buf[b + 1] + buf[a + 2] * buf[b + 2] + buf[a + 3] * buf[b + 3];
      if (d < 0) { buf[b] = -buf[b]; buf[b + 1] = -buf[b + 1]; buf[b + 2] = -buf[b + 2]; buf[b + 3] = -buf[b + 3]; }
    }
    tracks.push(new THREE.QuaternionKeyframeTrack(`${bone}.quaternion`, Float32Array.from(times), buf));
  }

  // --- hips translation ---------------------------------------------------
  if (!def.upper) {
    const rest = rig.restLocal.hips.pos;
    let vals, times;
    if (hipsPos.length) {
      hipsPos.sort((a, b) => a[0] - b[0]);
      vals = resample(hipsPos, dur, outTimes, !!def.loop, 3);
      times = outTimes;
    } else {
      vals = [[0, 0, 0], [0, 0, 0]];
      times = [0, dur];
    }
    const buf = new Float32Array(times.length * 3);
    for (let i = 0; i < times.length; i++) {
      // Deltas stay in character units so a taller soldier crouches
      // proportionally lower — and clips remain shareable per body type.
      buf[i * 3] = rest.x + vals[i][0];
      buf[i * 3 + 1] = rest.y + vals[i][1];
      buf[i * 3 + 2] = rest.z + vals[i][2];
    }
    tracks.push(new THREE.VectorKeyframeTrack('hips.position', Float32Array.from(times), buf));
  }

  const clip = new THREE.AnimationClip(name, dur, tracks);
  clip.userData = { meta: CLIP_META[name] };
  return clip;
}

