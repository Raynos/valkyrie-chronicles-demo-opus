// src/actors/anim.js
// -----------------------------------------------------------------------------
// Keyframe animation for the Gallian militia: clips authored in code as bone
// pose tables, compiled into THREE.AnimationClips, plus an Animator that layers
// an additive upper-body aim, head look-at, and two-bone foot IK on top of a
// speed-driven locomotion blend.
//
// AUTHORING CONVENTIONS
// ---------------------
// Poses are *deltas from the rest pose*, in DEGREES, as XYZ Euler triples in
// each bone's own rest frame (see rig.js basisQuat). Because every bone's rest
// frame puts +Y down the bone and +Z forward, the signs are uniform:
//
//     +X   swings the bone FORWARD  (hip flexion, elbow flexion, spine bend)
//     +Y   twists / yaws toward the character's LEFT
//     +Z   swings toward the character's LEFT (abduction on the left limb,
//          adduction on the right) — so mirroring is (x, -y, -z).
//
// FOOT PLANT RULE: because thigh/shin/foot all rotate about the same world axis,
// the sole stays parallel to the ground when  thigh.x + shin.x + foot.x == 0.
// A positive sum lifts the toes (heel strike), a negative sum points them
// (toe-off). Every leg pose below is written against that identity.
// -----------------------------------------------------------------------------

